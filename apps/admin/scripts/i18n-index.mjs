// Writes the catalogs' index from the folders under `messages/`: one module per language
// (`messages/<language>.generated.ts`, its namespaces merged), the list of languages with
// their lazy loaders (`messages/languages.generated.ts`) and Astryx's own catalogs for
// those languages with the admin's supplements to them (`messages/astryx.generated.ts`,
// `scripts/astryx-catalogs.mjs`). A namespace is a file,
// `messages/en/<namespace>.json`: adding one and running this registers it, with no list
// to edit by hand. Written as plain static imports, so Vite and Next.js build it alike.
//
//   node scripts/i18n-index.mjs           write
//   node scripts/i18n-index.mjs --check   fail when what's committed is stale

import { readFile, readdir, writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import process from "node:process";

import { PSEUDO, SUPPLEMENTS, astryxOf, supplementedLanguages } from "./astryx-catalogs.mjs";

const SOURCE = "en";
const root = join(import.meta.dirname, "..", "messages");
const check = process.argv.includes("--check");

const NAMESPACE = /^[a-z][a-z0-9_]*$/;
// A namespace's name is its import's name in the generated module.
const RESERVED = new Set(
  "break case catch class const continue debugger default delete do else enum export extends false finally for function if implements import in instanceof interface let new null package private protected public return static super switch this throw true try typeof var void while with yield await async".split(
    " ",
  ),
);
const banner =
  "// Generated by scripts/i18n-index.mjs (`pnpm --filter admin i18n:index`). Don't edit.\n";

/** A language's namespaces, sorted, from its folder's file names. */
async function namespacesOf(language) {
  const files = await readdir(join(root, language));
  return files
    .filter((file) => file.endsWith(".json"))
    .map((file) => file.slice(0, -".json".length))
    .toSorted();
}

/** A language's messages by full key (`<namespace>.<key>`), read from its folder. */
async function messagesOf(language, namespaces) {
  const messages = {};
  for (const ns of namespaces) {
    const file = JSON.parse(await readFile(join(root, language, `${ns}.json`), "utf8"));
    for (const [key, message] of Object.entries(file)) messages[`${ns}.${key}`] = message;
  }
  return messages;
}

/**
 * A language's module. `missing` is English for the keys the language lacks, written
 * into the module: the browser gets this one catalog, so a key still to be translated
 * reads in English there rather than as its key. CI keeps a shipped language complete
 * (`i18n:check`); this is for the time between.
 */
function languageModule(language, namespaces, missing = {}) {
  const imports = namespaces.map((ns) => `import ${ns} from "./${language}/${ns}.json";`);
  const filled = Object.entries(missing).map(
    ([key, message]) => `  ${JSON.stringify(key)}: ${JSON.stringify(message)},`,
  );
  return [
    banner,
    'import { mergeCatalogs } from "@hyphacommerce/i18n";',
    "",
    ...imports,
    "",
    `/** The ${language} catalog's files, by namespace. */`,
    `export const namespaces = { ${namespaces.join(", ")} };`,
    "",
    ...(filled.length > 0
      ? [
          `/** English, for the keys ${language} doesn't have yet. */`,
          "const untranslated: Record<string, string> = {",
          ...filled,
          "};",
          "",
          `/** The ${language} catalog: every key, in English where it isn't translated yet. */`,
          "export default { ...untranslated, ...mergeCatalogs(namespaces) };",
        ]
      : [
          `/** The ${language} catalog: every namespace, keys as \`<namespace>.<key>\`. */`,
          "export default mergeCatalogs(namespaces);",
        ]),
    "",
  ].join("\n");
}

function languagesModule(languages) {
  const loaders = languages.map(
    (language) =>
      `  ${JSON.stringify(language)}: async () => (await import("./${language}.generated")).default,`,
  );
  return [
    banner,
    'import type { Messages } from "@hyphacommerce/i18n";',
    "",
    "/** The languages the admin has catalogs for, English (the source) first. */",
    `export const LANGUAGES = ${JSON.stringify(languages)} as const;`,
    "",
    "export type AppLanguage = (typeof LANGUAGES)[number];",
    "",
    "/** Each language's catalog as a chunk of its own, loaded when a request or a browser asks. */",
    "export const LOADERS: Record<AppLanguage, () => Promise<Messages>> = {",
    ...loaders,
    "};",
    "",
  ].join("\n");
}

function astryxModule(languages, supplemented) {
  const loaders = [...languages, PSEUDO].flatMap((language) => {
    const name = language === SOURCE ? undefined : astryxOf(language);
    return name
      ? [
          `  ${JSON.stringify(language)}: () => import("@astryxdesign/core/locales/${name}.generated.js"),`,
        ]
      : [];
  });
  const supplements = supplemented.map(
    (language) =>
      `  ${JSON.stringify(language)}: () => import("../${basename(SUPPLEMENTS)}/${language}.json"),`,
  );
  return [
    banner,
    "type AstryxCatalog = Readonly<Record<string, string>>;",
    "",
    "/**",
    " * Astryx's own catalog for each of the admin's languages it ships one for, as a chunk of",
    " * its own. English is built into Astryx; a language missing here speaks Astryx's English.",
    " */",
    "export const ASTRYX_LOADERS: Readonly<",
    "  Record<string, () => Promise<{ default: AstryxCatalog }>>",
    "> = {",
    ...loaders,
    "};",
    "",
    "/**",
    " * The admin's own translations of the Astryx strings a language's shipped catalog lacks",
    ` * (\`${basename(SUPPLEMENTS)}/<language>.json\`), merged over it.`,
    " */",
    "export const ASTRYX_SUPPLEMENTS: Readonly<",
    "  Record<string, () => Promise<{ default: AstryxCatalog }>>",
    "> = {",
    ...supplements,
    "};",
    "",
  ].join("\n");
}

const entries = await readdir(root, { withFileTypes: true });
const folders = entries.filter((entry) => entry.isDirectory()).map((entry) => entry.name);
if (!folders.includes(SOURCE)) throw new Error(`messages/${SOURCE} is missing`);
const languages = [SOURCE, ...folders.filter((name) => name !== SOURCE).toSorted()];

const outputs = new Map();
const english = await messagesOf(SOURCE, await namespacesOf(SOURCE));
for (const language of languages) {
  const namespaces = await namespacesOf(language);
  const bad = namespaces.filter((ns) => !NAMESPACE.test(ns) || RESERVED.has(ns));
  if (bad.length > 0) {
    throw new Error(
      `messages/${language}: a namespace is lower-case letters, digits and "_", and not a JavaScript keyword: ${bad.join(", ")}`,
    );
  }
  const own = language === SOURCE ? english : await messagesOf(language, namespaces);
  const missing = Object.fromEntries(
    Object.entries(english).filter(([key]) => !Object.hasOwn(own, key)),
  );
  outputs.set(`${language}.generated.ts`, languageModule(language, namespaces, missing));
}
outputs.set("languages.generated.ts", languagesModule(languages));
const supplemented = await supplementedLanguages();
const orphans = supplemented.filter((language) => !languages.includes(language));
if (orphans.length > 0) {
  throw new Error(
    `${basename(SUPPLEMENTS)}/: no admin language for ${orphans.map((l) => `${l}.json`).join(", ")}`,
  );
}
outputs.set("astryx.generated.ts", astryxModule(languages, supplemented));

// A module of a language whose folder is gone would be imported by nothing, but would
// keep type-checking against files that no longer exist.
const leftover = entries
  .filter((entry) => entry.isFile() && entry.name.endsWith(".generated.ts"))
  .map((entry) => entry.name)
  .filter((name) => !outputs.has(name));

let isStale = leftover.length > 0;
for (const [name, content] of outputs) {
  const path = join(root, name);
  const current = await readFile(path, "utf8").catch(() => null);
  if (current === content) continue;
  isStale = true;
  if (!check) await writeFile(path, content);
}

if (check && isStale) {
  console.error(
    "messages/*.generated.ts are stale: run `pnpm --filter admin i18n:index` and commit the result.",
  );
  if (leftover.length > 0) console.error(`No longer needed: ${leftover.join(", ")}`);
  process.exit(1);
}
if (!check && leftover.length > 0) {
  console.warn(`Delete: ${leftover.map((name) => `messages/${name}`).join(", ")}`);
}
