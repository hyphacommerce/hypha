// Generates src/generated/{admin,storefront}.ts from the OpenAPI documents in
// ../../openapi (which the Rust host writes: `cargo run -p hypha-host-axum -- openapi`).
// With --check, fails instead of writing when a committed file is out of date.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { NULL, STRING, astToString, tsUnion } from "openapi-typescript";

const root = new URL("../../../", import.meta.url);
const out = new URL("../src/generated/", import.meta.url);
const check = process.argv.includes("--check");

const header =
  "// Generated by packages/sdk/scripts/generate.mjs from openapi/%s.json. Don't edit:\n" +
  "// run `pnpm sdk:generate` after `cargo run -p hypha-host-axum -- openapi`.\n\n";

// Enums the API marks open (`x-hypha-open-enum`) may gain values, so they become
// `string`: a value added later is never a type error, and clients must handle one
// they don't know. The known values are in the doc comment (the API's description
// lists them). Not `"a" | "b" | (string & {})`: openapi-fetch's `Readable<T>` maps
// over `string & {}` as if it were an object and mangles it.
const OPEN_ENUM = "x-hypha-open-enum";

function transform(schema) {
  if (schema[OPEN_ENUM] !== true || !Array.isArray(schema.enum)) return undefined;
  const nullable = Array.isArray(schema.type) && schema.type.includes("null");
  return nullable ? tsUnion([STRING, NULL]) : STRING;
}

let stale = [];
for (const name of ["admin", "storefront"]) {
  const source = new URL(`openapi/${name}.json`, root);
  const ast = await openapiTS(source, { transform });
  const text = header.replace("%s", name) + astToString(ast);
  const target = new URL(`${name}.ts`, out);
  if (check) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== text) stale.push(fileURLToPath(target));
  } else {
    await writeFile(target, text);
    console.log(`wrote ${fileURLToPath(target)}`);
  }
}
if (stale.length > 0) {
  console.error(`out of date (run \`pnpm sdk:generate\`):\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
