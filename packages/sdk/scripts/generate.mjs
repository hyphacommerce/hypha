// Generates src/generated/{admin,storefront}.ts from the OpenAPI documents in
// ../../openapi (which the Rust host writes: `cargo run -p hypha-host-axum -- openapi`).
// With --check, fails instead of writing when a committed file is out of date.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = new URL("../../../", import.meta.url);
const out = new URL("../src/generated/", import.meta.url);
const check = process.argv.includes("--check");

const header =
  "// Generated by packages/sdk/scripts/generate.mjs from openapi/%s.json. Don't edit:\n" +
  "// run `pnpm sdk:generate` after `cargo run -p hypha-host-axum -- openapi`.\n\n";

let stale = [];
for (const name of ["admin", "storefront"]) {
  const source = new URL(`openapi/${name}.json`, root);
  const ast = await openapiTS(source);
  const text = header.replace("%s", name) + astToString(ast);
  const target = new URL(`${name}.ts`, out);
  if (check) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== text) stale.push(fileURLToPath(target));
  } else {
    await writeFile(target, text);
    console.log(`wrote ${fileURLToPath(target)}`);
  }
}
if (stale.length > 0) {
  console.error(`out of date (run \`pnpm sdk:generate\`):\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
