// Writes src/generated/extensions.ts from openapi/extensions.json, the document the Rust
// host writes from hypha-extensions' DTOs. With --check, fails instead of writing when the
// committed file is out of date.
//
// Each extension point is an operation, under `webhooks` (keyed by the point's name) or
// `paths`. Its name and version come from `x-hypha-extension: {point, version}` when the
// operation has it; otherwise the name is the webhook's key, or the path without its
// slashes and a trailing `/v<n>`, and the version that `/v<n>` (1 without one). The
// request is the operation's JSON request body, the response its 200's JSON body; when a
// point has several versions, the newest is the one handlers are typed with.
//
// The document is committed (`cargo run -p hypha-host-axum -- openapi` writes it):
// without it, generating fails.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const source = new URL("../../../openapi/extensions.json", import.meta.url);
const target = new URL("../src/generated/extensions.ts", import.meta.url);
const check = process.argv.includes("--check");

const HEADER =
  "// Generated by packages/app/scripts/generate.ts from openapi/extensions.json. Don't edit:\n" +
  "// run `pnpm --filter @hyphacommerce/app generate` after `cargo run -p hypha-host-axum -- openapi`.\n\n";

const METHODS = ["get", "put", "post", "delete", "patch"] as const;

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

type Point = { name: string; version: number; access: string };

/** The points in the document, newest version per name. */
function points(document: Record<string, unknown>): Point[] {
  const found = new Map<string, Point>();
  const add = (point: Point) => {
    const known = found.get(point.name);
    if (!known || known.version < point.version) found.set(point.name, point);
  };
  for (const [section, root] of [
    ["webhooks", "webhooks"],
    ["paths", "paths"],
  ] as const) {
    const items = document[section];
    if (!isRecord(items)) continue;
    for (const [key, item] of Object.entries(items)) {
      if (!isRecord(item)) continue;
      for (const method of METHODS) {
        const operation = item[method];
        if (!isRecord(operation)) continue;
        const extension = operation["x-hypha-extension"];
        const declared = isRecord(extension) ? extension : {};
        const versioned = /^\/?(.+?)(?:\/v(\d+))?\/?$/.exec(key);
        const inferred =
          section === "webhooks" ? key : (versioned?.[1] ?? key).replaceAll("/", ".");
        const name = typeof declared.point === "string" ? declared.point : inferred;
        const version =
          typeof declared.version === "number" ? declared.version : Number(versioned?.[2] ?? 1);
        add({
          name,
          version,
          access: `${root}[${JSON.stringify(key)}][${JSON.stringify(method)}]`,
        });
      }
    }
  }
  return [...found.values()].toSorted((a, b) => a.name.localeCompare(b.name));
}

async function render(): Promise<string> {
  const text = await readFile(source, "utf8").catch(() => undefined);
  if (text === undefined)
    throw new Error(
      "openapi/extensions.json is missing: run `cargo run -p hypha-host-axum -- openapi`",
    );
  const document: unknown = JSON.parse(text);
  if (!isRecord(document)) throw new Error("openapi/extensions.json isn't a JSON object");
  const ast = await openapiTS(new URL(source));
  const map = points(document)
    .map(
      ({ name, version, access }) =>
        `  ${JSON.stringify(name)}: {\n` +
        `    version: ${version};\n` +
        `    request: NonNullable<${access}["requestBody"]>["content"]["application/json"];\n` +
        `    response: ${access}["responses"][200]["content"]["application/json"];\n` +
        `  };\n`,
    )
    .join("");
  return (
    HEADER +
    astToString(ast) +
    `\n/** Each point's newest version and bodies. */\nexport interface ExtensionPoints {\n${map}}\n`
  );
}

const text = await render();
if (check) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== text) {
    console.error(
      `out of date (run \`pnpm --filter @hyphacommerce/app generate\`):\n  ${fileURLToPath(target)}`,
    );
    process.exit(1);
  }
} else {
  await writeFile(target, text);
  console.log(`wrote ${fileURLToPath(target)}`);
}
