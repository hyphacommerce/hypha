/** The strings the API puts in a context itself (`context.json`), Rust's field names. */
const CONTEXT_STRINGS = [
  "cancel_customer",
  "cancel_inventory",
  "cancel_fraud",
  "cancel_declined",
  "cancel_staff",
  "manual_payment",
] as const;

function oneLine(email: Email, what: string, value: string): string {
  // Written into HTML as is (the layout's preheader), so no markup or entities.
  if (/[\n<>&]/.test(value))
    throw new Error(`${email.key}'s ${what} must be one line of plain text`);
  return value;
}

/** Where a language's files go in `crates/hypha-notifications/defaults/`: English at the top. */
export const folder = (language: string) => (language === "en" ? "" : `${language}/`);

async function renderEmail(email: Email, files: Map<string, string>, prefix: string) {
  const { Content } = email;
  const content = await toJinja(<Content />, { document: false });
  files.set(`${prefix}${email.key}.subject.j2`, oneLine(email, "subject", email.subject));
  files.set(
    `${prefix}${email.key}.html.j2`,
    `{% extends "layout" %}\n\n` +
      `{% block preheader %}${oneLine(email, "preheader", email.preheader)}{% endblock %}\n\n` +
      `{% block content %}\n${content}{% endblock %}\n`,
  );
  files.set(`${prefix}${email.key}.txt.j2`, email.text);
}

const rustString = (text: string) => JSON.stringify(text);

/** `order_confirmation` → `OrderConfirmation`: the key's `TemplateKey` variant. */
const pascal = (key: string) =>
  key.replace(/(^|_)([a-z])/g, (_, __: string, c: string) => c.toUpperCase());

/**
 * The Rust that embeds what was built (`src/generated/defaults.rs`): each language's
 * templates and context strings. Written as rustfmt writes it, so the committed file is
 * fmt-clean without running it.
 */
function rustIndex(catalogs: Map<string, Catalog>): string {
  const languages = ["en", ...[...catalogs.keys()].filter((l) => l !== "en").toSorted()];
  const english = templates
    .map((t) => `        TemplateKey::${pascal(t.key)} => sources!(${rustString(t.key)}),`)
    .join("\n");
  const others = languages
    .filter((language) => language !== "en")
    .flatMap((language) =>
      templates
        .filter((template) => template.translated)
        .map((t) => {
          const head = `        (${rustString(language)}, TemplateKey::${pascal(t.key)}) =>`;
          const value = `Some(sources!(${rustString(`${folder(language)}${t.key}`)}))`;
          // rustfmt's rule: the arm on one line when it fits in 100 columns, else a block.
          const line = `${head} ${value},`;
          return line.length <= 100 ? line : `${head} {\n            ${value}\n        }`;
        }),
    )
    .join("\n");
  const strings = languages
    .map((language) => {
      const catalog = catalogs.get(language) ?? {};
      const fields = CONTEXT_STRINGS.map((name) => {
        const value = catalog[`context.${name}`];
        if (value === undefined) throw new Error(`${language}: no context.${name}`);
        return `            ${name}: ${rustString(value)},`;
      }).join("\n");
      return `    (\n        ${rustString(language)},\n        ContextStrings {\n${fields}\n        },\n    ),`;
    })
    .join("\n");
  return `// @generated by packages/emails (\`pnpm emails:build\`) from its templates and the catalogs
// in packages/emails/messages. Do not edit: build again.

use crate::{
    TemplateKey,
    defaults::{ContextStrings, DefaultTemplate},
};

/// \`defaults/<path>.subject.j2\`, \`.html.j2\` and \`.txt.j2\`.
macro_rules! sources {
    ($path:literal) => {
        DefaultTemplate {
            subject: include_str!(concat!("../../defaults/", $path, ".subject.j2")),
            html: include_str!(concat!("../../defaults/", $path, ".html.j2")),
            text: Some(include_str!(concat!("../../defaults/", $path, ".txt.j2"))),
        }
    };
}

/// The languages the build has defaults in, English first.
pub(crate) const LANGUAGES: &[&str] = &[${languages.map(rustString).join(", ")}];

/// An English default: every key has one.
pub(crate) fn english(key: TemplateKey) -> DefaultTemplate {
    match key {
        TemplateKey::Layout => DefaultTemplate {
            subject: "",
            html: include_str!("../../defaults/layout.html.j2"),
            text: None,
        },
${english}
    }
}

/// The default of \`key\` in \`language\` (not English): the buyer's emails have one.
pub(crate) fn translated(language: &str, key: TemplateKey) -> Option<DefaultTemplate> {
    match (language, key) {
${others}
        _ => None,
    }
}

/// The text the API writes into a context itself, per language.
pub(crate) static CONTEXT_STRINGS: &[(&str, ContextStrings)] = &[
${strings}
];
`;
}

/**
 * File (relative to `crates/hypha-notifications/`) → contents: the defaults under
 * `defaults/` (other languages in a folder each) and the Rust index of them.
 */
export async function renderAll(): Promise<Map<string, string>> {
  const catalogs = await loadCatalogs();
  const problems = compareCatalogs(catalogs);
  if (problems.length > 0)
    throw new Error(`the catalogs don't match English:\n  ${problems.join("\n  ")}`);
  const files = new Map<string, string>();
  const defaults = new Map<string, string>();
  defaults.set("layout.html.j2", await toJinja(<Layout />, { document: true }));
  for (const [language, catalog] of catalogs) {
    const t = translator(language, catalog);
    for (const template of templates) {
      if (language !== "en" && !template.translated) continue;
      await renderEmail(template.email(t), defaults, folder(language));
    }
  }
  for (const [name, text] of defaults) files.set(`defaults/${name}`, text);
  files.set("src/generated/defaults.rs", rustIndex(catalogs));
  return files;
}
