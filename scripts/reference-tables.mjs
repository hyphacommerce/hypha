#!/usr/bin/env node
// Regenerates core's reference tables (design note 0021, SU1, SU2, Q4):
//   crates/hypha-core/src/tables/currencies.rs  ISO 4217, SIX's "list one"
//   crates/hypha-core/src/tables/countries.rs   ISO 3166-1 alpha-2, Debian's iso-codes
//   crates/hypha-core/src/tables/timezones.rs   IANA names, from a tzdata.zi
// English names come from CLDR, through this Node's ICU (what `Intl.DisplayNames("en")`
// shows), so the CLI and agents name things the way the admin's fallback does.
//
//   node scripts/reference-tables.mjs [path/to/zoneinfo]
//
// The zoneinfo directory holds `tzdata.zi` and `+VERSION` (macOS and most Linux
// distributions ship it as /usr/share/zoneinfo, the default; elsewhere, unpack IANA's
// tzdata tarball and run `make tzdata.zi`). No dependencies: Node 18 or later.
//
// Removing a code from a table stops stored rows that use it from loading: before
// committing a removal, add a migration that checks for it (see 0040_reference_codes.sql).

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const CURRENCIES_URL =
  "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml";
const COUNTRIES_URL =
  "https://salsa.debian.org/iso-codes-team/iso-codes/-/raw/main/data/iso_3166-1.json";
const OUT = new URL("../crates/hypha-core/src/tables/", import.meta.url);

const zoneinfo = process.argv[2] ?? "/usr/share/zoneinfo";
const icu = `CLDR ${process.versions.cldr} (ICU ${process.versions.icu})`;

/** A Rust string literal. Names are printable text; anything else is a bug upstream. */
function rust(s) {
  if (/[\u0000-\u001f\u007f]/.test(s)) throw new Error(`control character in ${JSON.stringify(s)}`);
  return `"${s.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

/** Sorted by code, byte-wise (what Rust's `str` ordering and binary search use). */
function sorted(rows) {
  for (const [code] of rows) if (!/^[\x21-\x7e]+$/.test(code)) throw new Error(`non-ASCII code ${code}`);
  rows.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  for (let i = 1; i < rows.length; i++) {
    if (rows[i - 1][0] === rows[i][0]) throw new Error(`${rows[i][0]} twice`);
  }
  return rows;
}

function write(file, header, type, name, rows, line) {
  const body = rows.map((r) => `    ${line(r)},\n`).join("");
  const text =
    `// @generated by scripts/reference-tables.mjs; don't edit by hand.\n` +
    header.map((h) => `// ${h}\n`).join("") +
    `\n#[rustfmt::skip]\npub(crate) static ${name}: [${type}; ${rows.length}] = [\n${body}];\n`;
  writeFileSync(new URL(file, OUT), text);
  console.log(`${file}: ${rows.length}`);
}

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}

// ---- currencies: every code with minor units that isn't a fund ----
{
  const xml = await fetchText(CURRENCIES_URL);
  const published = /Pblshd="([^"]+)"/.exec(xml)?.[1] ?? "unknown";
  const names = new Intl.DisplayNames("en", { type: "currency", fallback: "none" });
  const rows = new Map();
  for (const entry of xml.split("<CcyNtry>").slice(1)) {
    const code = /<Ccy>([A-Z]{3})<\/Ccy>/.exec(entry)?.[1];
    const units = /<CcyMnrUnts>([^<]+)<\/CcyMnrUnts>/.exec(entry)?.[1];
    // Funds (IsFund) and units without minor units (metals, bond units, XDR, test codes,
    // XXX) aren't money a shop charges in.
    if (!code || /IsFund="true"/.test(entry) || units === "N.A.") continue;
    if (!/^[0-9]$/.test(units)) throw new Error(`${code}: minor units ${units}`);
    const name = names.of(code);
    if (!name) throw new Error(`${code}: no English name in ${icu}`);
    rows.set(code, [code, Number(units), name]);
  }
  write(
    "currencies.rs",
    [
      `ISO 4217 list one, published ${published}, without funds and units that have no minor`,
      `units (metals, bond units, XDR, XSU, XUA, XTS, XXX). Names: ${icu}.`,
      `(code, minor units, English name), sorted by code.`,
    ],
    "(&str, u8, &str)",
    "CURRENCIES",
    sorted([...rows.values()]),
    ([code, units, name]) => `(${rust(code)}, ${units}, ${rust(name)})`,
  );
}

// ---- countries: the assigned ISO 3166-1 alpha-2 codes ----
{
  const data = JSON.parse(await fetchText(COUNTRIES_URL))["3166-1"];
  const names = new Intl.DisplayNames("en", { type: "region", fallback: "none" });
  const rows = data.map(({ alpha_2: code }) => {
    const name = names.of(code);
    if (!name) throw new Error(`${code}: no English name in ${icu}`);
    return [code, name];
  });
  write(
    "countries.rs",
    [
      `ISO 3166-1 alpha-2, the officially assigned codes (Debian iso-codes, main). Names:`,
      `${icu}. (code, English name), sorted by code.`,
    ],
    "(&str, &str)",
    "COUNTRIES",
    sorted(rows),
    ([code, name]) => `(${rust(code)}, ${rust(name)})`,
  );
}

// ---- timezones: every zone and link name, without the Factory placeholder ----
{
  const zi = readFileSync(join(zoneinfo, "tzdata.zi"), "utf8");
  const version = readFileSync(join(zoneinfo, "+VERSION"), "utf8").trim();
  const rows = [];
  for (const line of zi.split("\n")) {
    const parts = line.split(" ");
    // "Z name …" is a zone, "L target name" a link (old names browsers still report).
    if (parts[0] === "Z") rows.push([parts[1]]);
    else if (parts[0] === "L") rows.push([parts[2]]);
  }
  write(
    "timezones.rs",
    [
      `IANA time zone names, tzdata ${version}: zones and links (backward names such as`,
      `Europe/Kiev included), without the Factory placeholder. Sorted.`,
    ],
    "&str",
    "TIMEZONES",
    sorted(rows.filter(([name]) => name !== "Factory")),
    ([name]) => rust(name),
  );
}
